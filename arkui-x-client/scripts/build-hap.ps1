param(
  [ValidateSet('debug', 'release')]
  [string]$BuildMode = 'debug',
  [string]$SdkPath
)

$ErrorActionPreference = 'Stop'

$devEcoRoot = if ($env:DEVECO_STUDIO_HOME) {
  $env:DEVECO_STUDIO_HOME
} else {
  'C:\Program Files\Huawei\DevEco Studio'
}

$hvigor = Join-Path $devEcoRoot 'tools\hvigor\bin\hvigorw.bat'
$nodeRoot = Join-Path $devEcoRoot 'tools\node'
$javaRoot = Join-Path $devEcoRoot 'jbr'
$devEcoSdkRoot = Join-Path $devEcoRoot 'sdk'
$projectRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path

. (Join-Path $PSScriptRoot 'arkuix-sdk-path.ps1')
$arkUiXSdkRoot = Resolve-ArkUiXSdkRoot -RequestedPath $SdkPath -ProjectRoot $projectRoot

foreach ($requiredPath in @($hvigor, $nodeRoot, $javaRoot, $devEcoSdkRoot)) {
  if (-not (Test-Path -LiteralPath $requiredPath)) {
    throw "Missing build dependency: $requiredPath"
  }
}

$env:NODE_HOME = $nodeRoot
$env:JAVA_HOME = $javaRoot
$env:DEVECO_SDK_HOME = $devEcoSdkRoot
$env:ARKUIX_SDK_HOME = $arkUiXSdkRoot
$env:Path = "$(Join-Path $javaRoot 'bin');$nodeRoot;$env:Path"

# HarmonyOS-mode Hvigor ignores local.properties for ArkUI-X and resolves the
# SDK from the process environment. Keep local.properties correct for the IDE,
# then stop old daemons so they cannot retain an environment from before the
# SDK was installed or the workspace was renamed.
$localProperties = Join-Path $projectRoot 'local.properties'
$normalizedSdkRoot = $arkUiXSdkRoot.Replace('\', '/')
$propertyLines = if (Test-Path -LiteralPath $localProperties) {
  @(Get-Content -LiteralPath $localProperties | Where-Object { $_ -notmatch '^\s*arkui-x\.dir\s*=' })
} else {
  @('# Generated by scripts/build-hap.ps1. Do not store secrets in this file.')
}
$propertyLines += "arkui-x.dir=$normalizedSdkRoot"
Set-Content -LiteralPath $localProperties -Value $propertyLines -Encoding utf8

& $hvigor --stop-daemon 2>$null

& $hvigor assembleHap --mode module -p product=default -p "buildMode=$BuildMode" --no-daemon --stacktrace
if ($LASTEXITCODE -ne 0) {
  exit $LASTEXITCODE
}

$artifactRoot = Join-Path $PSScriptRoot '..\entry\build\default\outputs\default'
$artifacts = Get-ChildItem -LiteralPath $artifactRoot -Filter '*.hap' -File -ErrorAction SilentlyContinue
if (-not $artifacts) {
  throw "Build completed but no HAP artifact was found in $artifactRoot."
}

$artifacts | Select-Object FullName, Length, LastWriteTime
