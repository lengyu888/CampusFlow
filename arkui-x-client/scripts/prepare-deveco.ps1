param(
  [string]$SdkPath,
  [switch]$RestartIDE
)

$ErrorActionPreference = 'Stop'

$devEcoRoot = if ($env:DEVECO_STUDIO_HOME) {
  $env:DEVECO_STUDIO_HOME
} else {
  'C:\Program Files\Huawei\DevEco Studio'
}
$hvigor = Join-Path $devEcoRoot 'tools\hvigor\bin\hvigorw.bat'
$ide = Join-Path $devEcoRoot 'bin\devecostudio64.exe'
$projectRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..')).Path
$localProperties = Join-Path $projectRoot 'local.properties'

. (Join-Path $PSScriptRoot 'arkuix-sdk-path.ps1')
$arkUiXSdkRoot = Resolve-ArkUiXSdkRoot -RequestedPath $SdkPath -ProjectRoot $projectRoot

foreach ($requiredPath in @($hvigor, $ide)) {
  if (-not (Test-Path -LiteralPath $requiredPath)) {
    throw "Missing DevEco dependency: $requiredPath"
  }
}

$sdkVersions = Get-ChildItem -LiteralPath $arkUiXSdkRoot -Directory -ErrorAction Stop |
  Where-Object { Test-Path -LiteralPath (Join-Path $_.FullName 'arkui-x\sdkConfig.json') }
if (-not $sdkVersions) {
  throw "No usable ArkUI-X SDK version was found under $arkUiXSdkRoot"
}

$normalizedSdkRoot = $arkUiXSdkRoot.Replace('\', '/')
$propertyLines = if (Test-Path -LiteralPath $localProperties) {
  @(Get-Content -LiteralPath $localProperties | Where-Object { $_ -notmatch '^\s*arkui-x\.dir\s*=' })
} else {
  @('# Generated by scripts/prepare-deveco.ps1. Do not store secrets in this file.')
}
$propertyLines += "arkui-x.dir=$normalizedSdkRoot"
Set-Content -LiteralPath $localProperties -Value $propertyLines -Encoding utf8

# Persist for future Windows sessions and also set the current process so a
# DevEco instance launched by this script is correct immediately.
[Environment]::SetEnvironmentVariable('ARKUIX_SDK_HOME', $arkUiXSdkRoot, 'User')
[Environment]::SetEnvironmentVariable('DEVECO_SDK_HOME', (Join-Path $devEcoRoot 'sdk'), 'User')
[Environment]::SetEnvironmentVariable('JAVA_HOME', (Join-Path $devEcoRoot 'jbr'), 'User')
$env:ARKUIX_SDK_HOME = $arkUiXSdkRoot
$env:DEVECO_SDK_HOME = Join-Path $devEcoRoot 'sdk'
$env:JAVA_HOME = Join-Path $devEcoRoot 'jbr'

# Notify Explorer and other shells that Windows user environment variables
# changed. Without this broadcast, an IDE reopened from an already-running
# Explorer process can inherit the old value until the next sign-in.
if (-not ('CampusFlow.EnvironmentBroadcast' -as [type])) {
  Add-Type -Namespace 'CampusFlow' -Name 'EnvironmentBroadcast' -MemberDefinition @'
    [System.Runtime.InteropServices.DllImport("user32.dll", CharSet = System.Runtime.InteropServices.CharSet.Auto, SetLastError = true)]
    public static extern System.IntPtr SendMessageTimeout(
      System.IntPtr hWnd,
      uint Msg,
      System.UIntPtr wParam,
      string lParam,
      uint fuFlags,
      uint uTimeout,
      out System.UIntPtr lpdwResult);
'@
}
$broadcastResult = [UIntPtr]::Zero
[void][CampusFlow.EnvironmentBroadcast]::SendMessageTimeout(
  [IntPtr]0xffff,
  0x001A,
  [UIntPtr]::Zero,
  'Environment',
  0x0002,
  5000,
  [ref]$broadcastResult
)

# A daemon keeps the environment inherited at its creation time. Stopping it
# is required after an SDK install, environment change, or workspace rename.
& $hvigor --stop-daemon 2>$null

$projectCache = Join-Path $projectRoot '.hvigor'
if (Test-Path -LiteralPath $projectCache) {
  $stalePath = 'Desktop\HW Agent\arkui-x-client'
  $hasStalePath = Get-ChildItem -LiteralPath $projectCache -File -Recurse -ErrorAction SilentlyContinue |
    Where-Object { Select-String -LiteralPath $_.FullName -SimpleMatch $stalePath -Quiet -ErrorAction SilentlyContinue } |
    Select-Object -First 1
  if ($hasStalePath) {
    Remove-Item -LiteralPath $projectCache -Recurse -Force
  }
}

Write-Host "ArkUI-X environment repaired. SDK: $arkUiXSdkRoot"
Write-Host "Project: $projectRoot"

if ($RestartIDE) {
  $runningIde = Get-Process -Name 'devecostudio64' -ErrorAction SilentlyContinue
  if ($runningIde) {
    throw 'DevEco Studio is still running. Save your work, exit it completely, then rerun with -RestartIDE.'
  }
  Start-Process -FilePath $ide -ArgumentList @(('"{0}"' -f $projectRoot))
}
